import type { DeviceProfile } from "../../../types/device";
import {
  REVIEWED_ON,
  compatibleModel,
  createProfileGroup,
  rect,
  type GroupIdentity,
  type ProfileGroup,
} from "./catalog";

const PHONE_SOURCE = "https://support.apple.com/108044";

type PhoneGroupInput = Omit<GroupIdentity, "sourceUrls"> & {
  sourceUrls?: string[];
  width: number;
  height: number;
  logicalWidth: number;
  logicalHeight: number;
  bodyWidth: number;
  bodyHeight: number;
  corner: number;
  cutout: DeviceProfile["cutout"]["type"];
  cutoutBounds?: DeviceProfile["cutout"]["boundsPx"];
  safeTop: number;
  safeBottom: number;
  dpr?: number;
};

function phone(input: PhoneGroupInput): ProfileGroup {
  const isClassic = input.cutout === "none";
  const dpr = input.dpr ?? input.width / input.logicalWidth;
  const safeSide = isClassic ? 0 : Math.round(16 * dpr);
  const representative = input.compatibleModels[0];

  return createProfileGroup(
    {
      id: input.id,
      model: input.model,
      compatibleModels: input.compatibleModels,
      previousIds: input.previousIds,
      sourceUrls: [PHONE_SOURCE, ...(input.sourceUrls ?? [])],
    },
    {
      brand: "Apple",
      platform: "iOS",
      category: "iphone",
      family: "iPhone",
      supportedOrientations: ["portrait", "landscape"],
      chassis: {
        physicalWidthMm: input.bodyWidth,
        physicalHeightMm: input.bodyHeight,
        screenDiagonalInches: representative.screenDiagonalInches,
        bezelStyle: isClassic ? "classic" : "edge-to-edge",
      },
      display: {
        physicalWidthPx: input.width,
        physicalHeightPx: input.height,
        logicalWidthPt: input.logicalWidth,
        logicalHeightPt: input.logicalHeight,
        devicePixelRatio: dpr,
        aspectRatio: input.width / input.height,
        orientation: "portrait",
        cornerRadiusPx: input.corner,
      },
      cutout: { type: input.cutout, boundsPx: input.cutoutBounds },
      safeArea: {
        insetsPx: {
          top: input.safeTop,
          right: safeSide,
          bottom: input.safeBottom,
          left: safeSide,
        },
        source: "derived",
      },
      overlays: {
        statusBar: rect(0, 0, input.width, input.safeTop),
        lockScreenClock: rect(
          input.width * 0.16,
          input.height * 0.11,
          input.width * 0.68,
          input.height * 0.16,
        ),
        homeIndicator: isClassic
          ? undefined
          : rect(
              input.width * 0.34,
              input.height - Math.max(42, input.safeBottom * 0.45),
              input.width * 0.32,
              Math.max(8, Math.round(5 * dpr)),
            ),
        bottomActions: isClassic
          ? undefined
          : [
              rect(input.width * 0.1, input.height * 0.87, input.width * 0.13, input.width * 0.13),
              rect(input.width * 0.77, input.height * 0.87, input.width * 0.13, input.width * 0.13),
            ],
      },
      wallpaperBehavior: {
        systemMayZoom: true,
        systemMayExtend: !isClassic,
        notes: ["System wallpaper placement can vary by iOS version and user settings."],
      },
      metadata: {
        lastVerified: REVIEWED_ON,
        accuracy: "high",
        notes: [
          "Display resolution is published; overlay and corner geometry are derived approximations.",
          "Grouped options share the same wallpaper canvas and obstruction geometry.",
        ],
      },
    },
  );
}

