type MacGroupInput = Omit<GroupIdentity, "sourceUrls"> & {
  sourceUrls: string[];
  category: "macbook" | "imac" | "display";
  width: number;
  height: number;
  dpr?: number;
  bodyWidth: number;
  bodyHeight: number;
  notch?: boolean;
};

function mac(input: MacGroupInput): ProfileGroup {
  const dpr = input.dpr ?? 2;
  const menuHeight = input.notch ? Math.round(input.height * 0.035) : Math.round(28 * dpr);
  const dockHeight = Math.round(input.height * 0.09);
  const notchWidth = Math.round(input.width * 0.085);
  const representative = input.compatibleModels[0];

  return createProfileGroup(
    {
      id: input.id,
      model: input.model,
      compatibleModels: input.compatibleModels,
      previousIds: input.previousIds,
      sourceUrls: input.sourceUrls,
    },
    {
      brand: "Apple",
      platform: "macOS",
      category: input.category,
      family:
        input.category === "display" ? "Display" : input.category === "imac" ? "iMac" : "MacBook",
      supportedOrientations: ["landscape"],
      chassis: {
        physicalWidthMm: input.bodyWidth,
        physicalHeightMm: input.bodyHeight,
        screenDiagonalInches: representative.screenDiagonalInches,
        bezelStyle: input.category === "macbook" ? "laptop" : "desktop-display",
      },
      display: {
        physicalWidthPx: input.width,
        physicalHeightPx: input.height,
        logicalWidthPt: Math.round(input.width / dpr),
        logicalHeightPt: Math.round(input.height / dpr),
        devicePixelRatio: dpr,
        aspectRatio: input.width / input.height,
        orientation: "landscape",
        cornerRadiusPx: input.notch ? 38 : 0,
      },
      cutout: {
        type: input.notch ? "notch" : "none",
        boundsPx: input.notch
          ? rect((input.width - notchWidth) / 2, 0, notchWidth, menuHeight)
          : undefined,
      },
      safeArea: {
        insetsPx: {
          top: menuHeight,
          right: Math.round(12 * dpr),
          bottom: dockHeight,
          left: Math.round(12 * dpr),
        },
        source: "derived",
      },
      overlays: {
        menuBar: rect(0, 0, input.width, menuHeight),
        dock: rect(
          input.width * 0.28,
          input.height - dockHeight,
          input.width * 0.44,
          dockHeight * 0.78,
        ),
      },
      wallpaperBehavior: {
        systemMayZoom: false,
        systemMayExtend: false,
        notes: [
          "macOS Fill, Fit, Stretch, and Center behavior is approximated by the editor fit modes.",
        ],
      },
      metadata: {
        lastVerified: REVIEWED_ON,
        accuracy: "high",
        notes: [
          "Published native display resolution with approximate menu bar, Dock, and notch regions.",
          "Grouped options share the same wallpaper canvas and obstruction geometry.",
        ],
      },
    },
  );
}

